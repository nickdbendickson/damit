#!/usr/bin/env python3
"""dump_damit_algorithm_help.py 1.0.0 - write the REAL DamIT Processing algorithm ids and parameters to
pierre/knowledge/ALGORITHM-HELP-DAMIT.md, so Pierre cites ids that exist (damit_run:rundam, damit:classify,
damit_screen:handoff ...) instead of inventing damit_runner / --no-refine.

It loads each DamIT provider from this repo in an offscreen QGIS (QT_QPA_PLATFORM=offscreen, a throw-away
profile, no plugin installed, no network, no model) and reads the algorithm definitions, so the dump can
never drift from the code. One short process, a few seconds, one thread.

  QT_QPA_PLATFORM=offscreen python3 dump_damit_algorithm_help.py              # writes the knowledge file
  python3 dump_damit_algorithm_help.py --check                                # exit 1 if the file is stale
  python3 dump_damit_algorithm_help.py --stdout

Needs the QGIS Python bindings (the plugin conda env, or the qgis/qgis CI container).
Without them it prints how to run it and exits 2: it never guesses ids.
"""
import argparse
import importlib
import os
import sys
import tempfile

VERSION = "1.0.0"
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(HERE, "..", "knowledge", "ALGORITHM-HELP-DAMIT.md")

# (python package, what it is). The provider class is found by name (*Provider).
PROVIDERS = [
    ("damit_screener", "DamIT Screener"),
    ("damit_runner", "DamIT Runner"),
    ("damit_hazard", "DamIT Hazard"),
    ("damit_hazardlite", "DamIT Hazard Lite"),
    ("damit_data", "DamIT Data"),
    ("damit_pmp", "DamIT PMP (NOAA Atlas 14)"),
]


def _start_qgis():
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    profile = tempfile.mkdtemp(prefix="damit_dump_profile_")
    os.environ["QGIS_CUSTOM_CONFIG_PATH"] = profile
    os.environ.setdefault("DAMIT_SETTINGS", os.path.join(profile, "damit_settings.json"))
    from qgis.core import QgsApplication
    app = QgsApplication([], False, profile)
    app.initQgis()
    return app


def _default(d):
    try:
        v = d.defaultValue()
    except Exception:                                   # noqa: BLE001
        return None
    return v


def _enum_options(d):
    try:
        return list(d.options())
    except Exception:                                   # noqa: BLE001
        return None


def describe(alg):
    """One algorithm as a dict from its QGIS definition."""
    from qgis.core import QgsProcessingParameterDefinition as PD
    params = []
    for d in alg.parameterDefinitions():
        fl = d.flags()
        params.append({
            "name": d.name(), "label": d.description(), "type": d.type(), "default": _default(d),
            "optional": bool(fl & PD.FlagOptional), "advanced": bool(fl & PD.FlagAdvanced),
            "options": _enum_options(d)})
    outs = [{"name": o.name(), "label": o.description(), "type": o.type()} for o in alg.outputDefinitions()]
    return {"name": alg.name(), "display": alg.displayName(), "group": alg.group(), "help": alg.shortHelpString(),
            "params": params, "outputs": outs}


def collect():
    """[{provider_id, provider_name, package, algorithms: [describe(...)]}] for every DamIT provider."""
    if REPO not in sys.path:
        sys.path.insert(0, REPO)
    out = []
    for pkg, label in PROVIDERS:
        mod = importlib.import_module(pkg + ".provider")
        classes = [v for k, v in vars(mod).items() if isinstance(v, type) and k.endswith("Provider")
                   and k != "QgsProcessingProvider" and v.__module__ == mod.__name__]
        prov = classes[0]()
        prov.loadAlgorithms()
        algs = sorted(prov.algorithms(), key=lambda a: a.name())
        out.append({"provider_id": prov.id(), "provider_name": label, "package": pkg,
                    "algorithms": [describe(a) for a in algs]})
    return out


def _val(v):
    if v is None or v == "":
        return "-"
    if isinstance(v, float):
        return ("%g" % v)
    return str(v).replace("\n", " ")


def render(data):
    L = ["# DamIT Processing algorithms (generated: do not edit)", "",
         "_Generated by `pierre/tools/dump_damit_algorithm_help.py` from the plugin code in an offscreen QGIS. These are "
         "the REAL algorithm ids and parameter names. A tool or switch that is not on this page does not exist: "
         "never invent one (`damit_runner`, `--no-refine` and `damit_screener_handoff` do not exist). "
         "Run one with `qgis_process run <id> --PARAM=value`; an enum parameter takes the 0-based index of its "
         "option; a boolean takes 1 or 0 (e.g. `--GRID_REFINE=0`)._", ""]
    ids = [("%s:%s" % (p["provider_id"], a["name"])) for p in data for a in p["algorithms"]]
    L += ["Algorithm ids: " + ", ".join("`%s`" % i for i in ids), ""]
    for p in data:
        L += ["## Provider `%s` - %s (package `%s`)" % (p["provider_id"], p["provider_name"], p["package"]), ""]
        for a in p["algorithms"]:
            L += ["### `%s:%s` - %s" % (p["provider_id"], a["name"], a["display"]), "", "Group: %s" % a["group"], ""]
            L += [a["help"].strip(), ""] if a["help"] else []
            L += ["| Parameter | Label | Type | Default | Notes |", "|---|---|---|---|---|"]
            for q in a["params"]:
                notes = []
                if q["optional"]:
                    notes.append("optional")
                if q["advanced"]:
                    notes.append("advanced")
                if q["options"]:
                    notes.append("options: " + "; ".join("%d=%s" % (i, o) for i, o in enumerate(q["options"])))
                L.append("| `%s` | %s | %s | %s | %s |" % (q["name"], q["label"].replace("|", "/"), q["type"],
                                                          _val(q["default"]).replace("|", "/"), "; ".join(notes) or "-"))
            if a["outputs"]:
                L += ["", "Outputs: " + ", ".join("`%s`" % o["name"] for o in a["outputs"])]
            L.append("")
    return "\n".join(L).rstrip() + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--check", action="store_true", help="exit 1 when the committed file differs from the code")
    ap.add_argument("--stdout", action="store_true")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    try:
        import qgis.core  # noqa: F401
    except ImportError:
        print("QGIS Python bindings not found. Run this in the QGIS python (conda env 'ndqgis' / the qgis/qgis "
              "container) with QT_QPA_PLATFORM=offscreen.", file=sys.stderr)
        return 2
    app = _start_qgis()
    try:
        text = render(collect())
    finally:
        app.exitQgis()
    if a.stdout:
        sys.stdout.write(text)
        return 0
    path = os.path.abspath(a.out)
    if a.check:
        try:
            with open(path, encoding="utf-8") as f:
                cur = f.read()
        except OSError:
            cur = ""
        if cur != text:
            print("%s is stale: rerun dump_damit_algorithm_help.py" % path, file=sys.stderr)
            return 1
        print("up to date")
        return 0
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
